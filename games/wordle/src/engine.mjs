export const normalize = (word) => word.toLowerCase().replaceAll('ё', 'е');
export function score(guess, answer) {
  const result = Array(5).fill('absent');
  const remaining = [...answer];
  [...guess].forEach((letter, i) => {
    if (letter === answer[i]) {
      result[i] = 'correct';
      remaining[i] = null;
    }
  });
  [...guess].forEach((letter, i) => {
    if (result[i] === 'correct') return;
    const found = remaining.indexOf(letter);
    if (found >= 0) {
      result[i] = 'present';
      remaining[found] = null;
    }
  });
  return result;
}
export const dayKey = (now = new Date()) => now.toISOString().slice(0, 10);
export function dailyAnswer(day) {
  // UTC date, shared worldwide; v1 pool must stay in the same order.
  const index = Math.floor(Date.parse(day + 'T00:00:00Z') / 86400000);
  return ANSWERS[
    (((index * 137 + 43) % ANSWERS.length) + ANSWERS.length) % ANSWERS.length
  ];
}
export function restore(raw, answer, allowed) {
  try {
    const state = JSON.parse(raw);
    if (!Array.isArray(state?.guesses) || state.guesses.length > 6) return [];
    const accepted = [];
    for (const guess of state.guesses) {
      if (
        typeof guess !== 'string' ||
        !allowed.has(guess) ||
        accepted.includes(guess) ||
        accepted.includes(answer)
      )
        return [];
      accepted.push(guess);
    }
    return accepted;
  } catch {
    return [];
  }
}
export function shareText(guesses, answer, label) {
  const squares = { correct: '🟩', present: '🟨', absent: '⬜' };
  return (
    `Пять букв · ${label}\n${guesses.includes(answer) ? guesses.length : 'X'}/6\n\n` +
    guesses
      .map((g) =>
        score(g, answer)
          .map((s) => squares[s])
          .join(''),
      )
      .join('\n') +
    '\n\nhttps://games.lvtd.dev/wordle/'
  );
}
